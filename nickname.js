// nickname.js — 랭킹용 닉네임 조합 생성기 (클라이언트·서버 공용)
//
// 왜 자유 입력을 없앴나 (2026-07-27, 불특정 다수 초등학생 공개 대비):
//   ① 개인정보 — "이름을 입력하세요"는 초등학생에게 실명을 쓰게 만든다. 그 실명이
//      공개 랭킹에 게시되고 400일 보관되면 만 14세 미만 아동 개인정보 처리가 된다.
//   ② 욕설 — 금지어 블랙리스트는 초성 변형·자모 분리·타인 이름 조합("○○○바보")에
//      반드시 뚫린다. 블랙리스트로는 이길 수 없는 싸움이다.
//   두 문제 모두 "조합형 생성"으로 구조적으로 사라진다. 아이는 고를 수만 있고,
//   서버는 이 목록으로 만들 수 있는 문자열만 받는다(화이트리스트).
//
// ⚠️ 목록을 고칠 때 지켜야 할 불변식:
//   - 형용사 ≤ 4자, 명사 ≤ 3자 → 최대 4+3+2 = 9자 (서버 name 길이 상한 10자 이내)
//   - 어떤 조합도 비속어·비하로 읽히지 않을 것 (전수로 눈으로 확인할 것)
//   - 목록을 바꾸면 과거 닉네임이 서버 검증에서 거절된다. 항목은 추가만 하고
//     삭제하지 말 것 (삭제하면 그 닉네임을 쓰던 아이가 등록 불가가 된다).

export const NICK_ADJ = [
  "용감한", "빠른", "씩씩한", "재빠른", "튼튼한", "신나는", "멋진", "상냥한",
  "든든한", "날쌘", "꿋꿋한", "명랑한", "다정한", "힘찬", "슬기로운", "반짝이는",
];

export const NICK_NOUN = [
  "호랑이", "사자", "여우", "곰", "수달", "펭귄", "부엉이", "고래", "다람쥐", "늑대",
  "거북이", "표범", "코끼리", "판다", "돌고래", "유니콘", "드래곤", "로봇", "별똥별", "매",
];

// 16 × 20 × 90 = 28,800가지
export const NICK_COMBINATIONS = NICK_ADJ.length * NICK_NOUN.length * 90;

/** 무작위 닉네임 하나. 예: "용감한호랑이42" */
export function generateNickname(rand = Math.random) {
  const a = NICK_ADJ[Math.floor(rand() * NICK_ADJ.length)];
  const n = NICK_NOUN[Math.floor(rand() * NICK_NOUN.length)];
  const num = 10 + Math.floor(rand() * 90); // 10~99 (2자리 고정)
  return `${a}${n}${num}`;
}

// 정규식 특수문자가 목록에 들어갈 일은 없지만, 목록을 나중에 손볼 때를 대비해 이스케이프한다.
const rx = (arr) => arr.map((s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
const NICK_RE = new RegExp(`^(?:${rx(NICK_ADJ)})(?:${rx(NICK_NOUN)})[1-9][0-9]$`);

/** 이 목록으로 만들 수 있는 닉네임인가 (서버 화이트리스트 — 직접 API 호출도 여기서 걸린다) */
export function isGeneratedNick(name) {
  return NICK_RE.test(String(name ?? ""));
}
